/** 记忆抽取的 JSON 输出要求 */
export const MEMORY_EXTRACT_JSON_HINT =
  '\n【输出格式】只输出 JSON：\n' +
  '{"memories":[{"text":"事实（陈述句）","scene":"当时的情境与氛围","meaning":0.8,"confidence":0.9,"evidence":"user：… / assistant：…"}]}\n' +
  '没有新经历时输出 {"memories":[]}。'

/** 角色卡摘要（供抽取器判断「是否与设定冲突」；限长以免抽取成本膨胀） */
export function cardBrief(char, maxChars = 900) {
  if (!char) return ''
  const parts = []
  if (char.name) parts.push('姓名：' + char.name)
  if (char.personality) parts.push('性格：' + char.personality)
  if (char.description) parts.push('描述：' + char.description)
  const s = parts.join('\n')
  return s.length > maxChars ? s.slice(0, maxChars) + '…' : s
}

/**
 * 记忆抽取的完整 system 提示词 = 通用规则 + 角色人设 + JSON 输出要求。
 *
 * 为何要把人设喂给抽取器：否则它无从判断某条事实「是否与人设相反」，
 * 也就落实不了「冲突必须带起因」这条规则（结果就是记忆平白无故跟角色卡打架）。
 *
 * ⚠️ 但这个做法有副作用：人设里会带**别的角色的名字**
 * （例如「父亲林用户甲」），模型会把它们当成对话里的人——对话里叫「用户甲」的恋人
 * 被认成了父亲「角色甲」。所以：① 表头明确写「**仅**用于判断是否相反」；
 * ② MEMORY_EXTRACT_SYSTEM 里加一条「不要把两边的人混成一个」+「名字必须在 evidence 里出现过」的自检。
 */
export function buildExtractSystem(character) {
  const brief = cardBrief(character)
  return (
    MEMORY_EXTRACT_SYSTEM +
    (brief
      ? '\n【角色人设（固定设定，**仅**用于判断某条事实是否与它相反）】\n' +
        '（这是设定，不是对话内容。里面提到的其他人**和对话里的人不是同一个人**，\n' +
        '除非对话里明说了；不要拿这里的名字去对应对话里的人。）\n' +
        brief
      : '') +
    MEMORY_EXTRACT_JSON_HINT
  )
}

